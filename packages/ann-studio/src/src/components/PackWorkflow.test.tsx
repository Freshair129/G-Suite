// @vitest-environment jsdom
import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import PackWorkflow from './PackWorkflow';
import { useStudioStore } from '../store/useStudioStore';
import { createPackProject } from '../lib/packProject';
const api = vi.hoisted(()=>({invoke:vi.fn(),save:vi.fn(),build:vi.fn(),snapshot:vi.fn(),cancel:vi.fn()}));
vi.mock('@tauri-apps/api/core',()=>({invoke:api.invoke}));
vi.mock('@tauri-apps/plugin-dialog',()=>({open:vi.fn(),save:api.save}));
vi.mock('../lib/exportGmaidenPack',()=>({buildCurrentGann:api.build,cancelCurrentGannBuild:api.cancel,subscribeBuildProgress:()=>()=>{}}));
vi.mock('../lib/project',()=>({saveProject:vi.fn(),openProject:vi.fn(),updateProjectMetadata:vi.fn(),selectProjectVariant:vi.fn(),updateVariant:vi.fn(),newProject:vi.fn(),addProjectAsset:vi.fn(),updateProjectBinding:vi.fn(),snapshotProject:api.snapshot,recoverProject:vi.fn(),importLegacyProject:vi.fn()}));
vi.mock('./BannerEditor',()=>({default:()=> <div>Editor</div>}));
vi.mock('./SourceView',()=>({default:()=> <div>Source</div>}));
vi.mock('./GannPackage',()=>({default:()=> <div>Packaged preview</div>}));
const artifact={path:'C:/test.gann',digest:'a'.repeat(64),pack_id:'ann_test',revision:1,events:1,clips:2,banners:2};
afterEach(cleanup);
beforeEach(()=>{useStudioStore.setState({projectDocument:null,projectGeneration:0});api.snapshot.mockReset();api.snapshot.mockResolvedValue({});api.cancel.mockReset();api.cancel.mockResolvedValue(undefined);api.invoke.mockReset();api.invoke.mockResolvedValue([]);api.save.mockReset();api.save.mockResolvedValue('C:/export.gann');api.build.mockReset();api.build.mockResolvedValue(artifact);});
it('exports the built bytes and disables use after another edit',async()=>{
  render(<PackWorkflow/>);
  fireEvent.click(screen.getByRole('button',{name:'5. สร้างและทดสอบ'}));
  fireEvent.click(screen.getByRole('button',{name:'สร้างและตรวจแพ็ก'}));
  await screen.findByText(/revision 1/);
  fireEvent.click(screen.getByRole('button',{name:'6. ใช้แพ็ก'}));
  fireEvent.click(screen.getByRole('button',{name:'ส่งออก .gann'}));
  await waitFor(()=>expect(api.invoke).toHaveBeenCalledWith('export_gann_artifact',{path:artifact.path,expectedDigest:artifact.digest,destination:'C:/export.gann'}));
  expect(api.build).toHaveBeenCalledTimes(1);
  fireEvent.click(screen.getByRole('button',{name:'1. โปรเจกต์'}));
  fireEvent.change(screen.getByLabelText('ชื่อแพ็ก'),{target:{value:'Changed'}});
  fireEvent.click(screen.getByRole('button',{name:'6. ใช้แพ็ก'}));
  expect((screen.getByRole('button',{name:'ส่งออก .gann'}) as HTMLButtonElement).disabled).toBe(true);
});
it('keeps export disabled and gives an error when build fails',async()=>{
  api.build.mockRejectedValueOnce(new Error('disk full'));
  render(<PackWorkflow/>);
  fireEvent.click(screen.getByRole('button',{name:'5. สร้างและทดสอบ'}));
  fireEvent.click(screen.getByRole('button',{name:'สร้างและตรวจแพ็ก'}));
  await screen.findByRole('alert');
  fireEvent.click(screen.getByRole('button',{name:'6. ใช้แพ็ก'}));
  expect((screen.getByRole('button',{name:'ส่งออก .gann'}) as HTMLButtonElement).disabled).toBe(true);
});
it('never offers the previous artifact after opening an equally named project',async()=>{
  const first=createPackProject();first.name='Same name';
  useStudioStore.setState({projectDocument:first,projectGeneration:0});
  render(<PackWorkflow/>);
  fireEvent.click(screen.getByRole('button',{name:'5. สร้างและทดสอบ'}));
  fireEvent.click(screen.getByRole('button',{name:'สร้างและตรวจแพ็ก'}));
  await screen.findByText(/revision 1/);
  const second=createPackProject();second.name=first.name;
  act(()=>useStudioStore.setState({projectDocument:second,projectGeneration:0}));
  fireEvent.click(screen.getByRole('button',{name:'6. ใช้แพ็ก'}));
  expect((screen.getByRole('button',{name:'ส่งออก .gann'}) as HTMLButtonElement).disabled).toBe(true);
  expect(screen.queryByText(/revision 1/)).toBeNull();
});
it('does not export an older project when it changes during the file dialog',async()=>{
  const first=createPackProject();useStudioStore.setState({projectDocument:first,projectGeneration:0});
  let choose!:(path:string)=>void;
  api.save.mockImplementation(()=>new Promise<string>(resolve=>{choose=resolve;}));
  render(<PackWorkflow/>);
  fireEvent.click(screen.getByRole('button',{name:'5. สร้างและทดสอบ'}));
  fireEvent.click(screen.getByRole('button',{name:'สร้างและตรวจแพ็ก'}));
  await screen.findByText(/revision 1/);
  fireEvent.click(screen.getByRole('button',{name:'6. ใช้แพ็ก'}));
  fireEvent.click(screen.getByRole('button',{name:'ส่งออก .gann'}));
  await waitFor(()=>expect(api.save).toHaveBeenCalled());
  act(()=>useStudioStore.setState({projectDocument:createPackProject(),projectGeneration:0}));
  await act(async()=>choose('C:/wrong-project.gann'));
  expect(api.invoke.mock.calls.some(call=>call[0]==='export_gann_artifact')).toBe(false);
  await screen.findByRole('alert');
});
it('can cancel while preparing a snapshot before a native job starts',async()=>{
  let finish!:(value:unknown)=>void;
  api.snapshot.mockImplementation(()=>new Promise(resolve=>{finish=resolve;}));
  render(<PackWorkflow/>);
  fireEvent.click(screen.getByRole('button',{name:'5. สร้างและทดสอบ'}));
  fireEvent.click(screen.getByRole('button',{name:'สร้างและตรวจแพ็ก'}));
  fireEvent.click(await screen.findByRole('button',{name:'ยกเลิกการสร้าง'}));
  await act(async()=>finish({}));
  expect(api.build).not.toHaveBeenCalled();
  expect(api.cancel).toHaveBeenCalled();
});
